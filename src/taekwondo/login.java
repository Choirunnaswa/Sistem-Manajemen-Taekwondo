public void cek_login()
{
    Connection kon = koneksi.koneksiDb();
    try {
        Statement st = kon.createStatement();
        String sql = "SELECT * FROM tbl_user WHERE user='" + user.getText() +
                     "' and pass='" + pass.getText() +
                     "' and level='" + Level.getSelectedItem() + "'";
        ResultSet rs = st.executeQuery(sql);

        if (rs.next()) {
            JOptionPane.showMessageDialog(null, "Login Berhasil");

            if (rs.getString("level").equals("anggota")) {
                new MenuAnggota().show();
                this.dispose();
            } else if (rs.getString("level").equals("pelatih")) {
                new MenuAdmin().show();
                this.dispose();
            }

        } else {
            JOptionPane.showMessageDialog(null, "Maaf Username atau Password Salah");
            user.setText("");
            pass.setText("");
            user.requestFocus();
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, e);
    }
}
